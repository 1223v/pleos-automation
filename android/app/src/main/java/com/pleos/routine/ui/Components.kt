/** Lucide icon from res/drawable (generated by design/android-resources.mjs). Decorative unless described. */
@Composable fun LucideIcon(@DrawableRes icon: Int, modifier: Modifier = Modifier, size: Dp = 24.dp, tint: Color = LocalContentColor.current, description: String? = null) =
    Icon(painterResource(icon), description, modifier.size(size), tint = tint)

/** Coloured square holding a category icon, the same tile the canvas nodes use. */
@Composable fun IconTile(@DrawableRes icon: Int, hue: Hue, size: Dp = 48.dp, modifier: Modifier = Modifier) {
    val h = astryx.hue(hue)
    Box(modifier.size(size).clip(RoundedCornerShape(AstryxRadius.element)).background(h.background), contentAlignment = Alignment.Center) {
        LucideIcon(icon, size = size * 0.52f, tint = h.icon)
    }
}

/** Surface card: white (or dark) panel on the body colour with a hairline border, Astryx container radius. */
@Composable fun Panel(modifier: Modifier = Modifier, padding: Dp = 20.dp, content: @Composable ColumnScope.() -> Unit) {
    val c = astryx
    Column(modifier.clip(RoundedCornerShape(AstryxRadius.container)).background(c.surface)
        .border(1.dp, c.borderEmphasized, RoundedCornerShape(AstryxRadius.container)).padding(padding),
        verticalArrangement = Arrangement.spacedBy(10.dp), content = content)
}

enum class Tone { INFO, SUCCESS, WARNING, ERROR, NEUTRAL }

private data class ToneColors(val fill: Color, val text: Color, @DrawableRes val icon: Int)

@Composable private fun tone(t: Tone): ToneColors {
    val c = astryx
    return when (t) {
        Tone.INFO -> ToneColors(c.infoMuted, c.onInfoMuted, R.drawable.ic_lucide_info)
        Tone.SUCCESS -> ToneColors(c.successMuted, c.onSuccessMuted, R.drawable.ic_lucide_circle_check)
        Tone.WARNING -> ToneColors(c.warningMuted, c.onWarningMuted, R.drawable.ic_lucide_triangle_alert)
        Tone.ERROR -> ToneColors(c.errorMuted, c.onErrorMuted, R.drawable.ic_lucide_circle_x)
        Tone.NEUTRAL -> ToneColors(c.hue(Hue.GRAY).background, c.textPrimary, R.drawable.ic_lucide_info)
    }
}

/** One-line status message with an icon, replacing coloured loose text. */
@Composable fun StatusBanner(text: String, tone: Tone, modifier: Modifier = Modifier, @DrawableRes icon: Int? = null) {
    val t = tone(tone)
    Row(modifier.fillMaxWidth().clip(RoundedCornerShape(AstryxRadius.element)).background(t.fill).padding(horizontal = 16.dp, vertical = 10.dp),
        horizontalArrangement = Arrangement.spacedBy(12.dp), verticalAlignment = Alignment.CenterVertically) {
        LucideIcon(icon ?: t.icon, size = 22.dp, tint = t.text)
        Text(text, color = t.text, style = MaterialTheme.typography.bodyMedium)
    }
}

/** Small pill: status, version, count. */
@Composable fun Pill(text: String, tone: Tone = Tone.NEUTRAL, @DrawableRes icon: Int? = null, large: Boolean = false) {
    val t = tone(tone)
    Row(Modifier.clip(CircleShape).background(t.fill).padding(horizontal = if (large) 16.dp else 12.dp, vertical = if (large) 8.dp else 4.dp),
        horizontalArrangement = Arrangement.spacedBy(if (large) 8.dp else 6.dp), verticalAlignment = Alignment.CenterVertically) {
        icon?.let { LucideIcon(it, size = if (large) 22.dp else 16.dp, tint = t.text) }
        Text(text, color = t.text, style = if (large) MaterialTheme.typography.labelLarge else MaterialTheme.typography.labelSmall, fontWeight = FontWeight.SemiBold)
    }
}

/** Section heading with a leading icon. */
@Composable fun SectionTitle(@DrawableRes icon: Int, text: String, modifier: Modifier = Modifier) {
    Row(modifier, horizontalArrangement = Arrangement.spacedBy(10.dp), verticalAlignment = Alignment.CenterVertically) {
        LucideIcon(icon, size = 24.dp, tint = astryx.iconPrimary)
        Text(text, style = MaterialTheme.typography.titleMedium)
    }
}

/** Chip colours for tabs and steps: the selected one takes the Astryx accent. */
@Composable fun routineChipColors() = FilterChipDefaults.filterChipColors(
    containerColor = astryx.surface, labelColor = astryx.textSecondary, iconColor = astryx.iconSecondary,
    selectedContainerColor = astryx.accent, selectedLabelColor = astryx.onAccent, selectedLeadingIconColor = astryx.onAccent,
)

/** Leading icon for buttons; text stays the label tests and drivers read. */
@Composable fun ButtonIcon(@DrawableRes icon: Int) {
    LucideIcon(icon, size = 20.dp)
    Spacer(Modifier.width(8.dp))
}
