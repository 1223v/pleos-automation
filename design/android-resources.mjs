// Generates the app's design resources from the same source as the application figures:
//  - android/app/src/main/res/drawable/ic_lucide_*.xml  (Lucide icons of the Astryx neutral theme, ISC)
//  - android/app/src/main/java/com/pleos/routine/ui/theme/AstryxTokens.kt  (neutral light/dark colours)
// Usage (from design/): node android-resources.mjs
import {mkdirSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {iconNodes, icons, lucideVersion, neutralTokens, themeVersion} from './flow-visuals.mjs';

const designDir = dirname(fileURLToPath(import.meta.url));
const app = resolve(designDir, '..', 'android', 'app', 'src', 'main');
const drawables = join(app, 'res', 'drawable');
const themeKt = join(app, 'java', 'com', 'pleos', 'routine', 'ui', 'theme', 'AstryxTokens.kt');

const num = v => Number(v);
const f = v => +(+v).toFixed(4);

/** Lucide SVG element -> VectorDrawable path data (VectorDrawable only knows <path>). */
function pathData([tag, a]) {
  switch (tag) {
    case 'path': return a.d;
    case 'line': return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case 'polyline':
    case 'polygon': {
      const p = a.points.trim().split(/[\s,]+/).map(num);
      let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`;
      return tag === 'polygon' ? d + 'Z' : d;
    }
    case 'circle':
    case 'ellipse': {
      const cx = num(a.cx ?? 0), cy = num(a.cy ?? 0), rx = num(a.r ?? a.rx), ry = num(a.r ?? a.ry);
      return `M${f(cx - rx)} ${cy}a${rx} ${ry} 0 1 0 ${f(2 * rx)} 0a${rx} ${ry} 0 1 0 ${f(-2 * rx)} 0`;
    }
    case 'rect': {
      const x = num(a.x ?? 0), y = num(a.y ?? 0), w = num(a.width), h = num(a.height);
      const rx = Math.min(num(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(num(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${f(x + rx)} ${y}h${f(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${f(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${-rx} ${ry}`
        + `h${f(-(w - 2 * rx))}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${f(-(h - 2 * ry))}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
    }
    default: throw new Error(`unsupported SVG element <${tag}>`);
  }
}

export const resName = name => `ic_lucide_${name.replace(/-/g, '_')}`;

async function writeIcons() {
  mkdirSync(drawables, {recursive: true});
  for (const old of readdirSync(drawables)) if (old.startsWith('ic_lucide_')) rmSync(join(drawables, old));
  const names = new Set([...Object.values(icons.kind), ...Object.values(icons.action), ...Object.values(icons.trigger), ...icons.ui, ...icons.app]);
  for (const name of [...names].sort()) {
    const paths = (await iconNodes(name)).map(n => `    <path\n        android:pathData="${pathData(n)}"\n        android:fillColor="#00000000"\n        android:strokeColor="#FF000000"\n        android:strokeWidth="2"\n        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />`).join('\n');
    writeFileSync(join(drawables, `${resName(name)}.xml`),
      `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by design/android-resources.mjs. Lucide "${name}" via lucide-react ${lucideVersion} (ISC). -->\n`
      + `<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n${paths}\n</vector>\n`);
  }
  return names.size;
}

/** CSS #rgb/#rrggbb/#rrggbbaa -> Compose Color(0xAARRGGBB) literal. */
function color(css) {
  let h = css.slice(1);
  if (h.length === 3) h = [...h].map(c => c + c).join('');
  const a = h.length === 8 ? h.slice(6) : 'ff';
  return `Color(0x${(a + h.slice(0, 6)).toUpperCase()})`;
}

function writeTokens() {
  const t = neutralTokens();
  const need = k => { if (!t[k]) throw new Error(`missing token ${k}`); return t[k]; };
  const roles = {
    body: '--color-background-body', surface: '--color-background-surface', card: '--color-background-card',
    popover: '--color-background-popover', textPrimary: '--color-text-primary', textSecondary: '--color-text-secondary',
    textDisabled: '--color-text-disabled', iconPrimary: '--color-icon-primary', iconSecondary: '--color-icon-secondary',
    accent: '--color-accent', onAccent: '--color-on-accent', border: '--color-border', borderEmphasized: '--color-border-emphasized',
    success: '--color-success', successMuted: '--color-success-muted', onSuccess: '--color-on-success',
    error: '--color-error', errorMuted: '--color-error-muted', onError: '--color-on-error',
    info: '--color-info', infoMuted: '--color-info-muted', onInfo: '--color-on-info',
    warning: '--color-warning', warningMuted: '--color-warning-muted', onWarning: '--color-on-warning',
  };
  const hues = ['blue', 'cyan', 'gray', 'green', 'orange', 'pink', 'purple', 'red', 'teal', 'yellow'];
  const scheme = mode => {
    const lines = Object.entries(roles).map(([k, v]) => `    ${k} = ${color(need(v)[mode])},`);
    const hueLines = hues.map(h => `        Hue.${h.toUpperCase()} to HueColors(${['background', 'icon', 'text', 'border'].map(p => color(need(`--color-${p}-${h}`)[mode])).join(', ')}),`);
    return `AstryxColors(\n${lines.join('\n')}\n    hues = mapOf(\n${hueLines.join('\n')}\n    ),\n)`;
  };
  mkdirSync(dirname(themeKt), {recursive: true});
  writeFileSync(themeKt, `// Generated by design/android-resources.mjs from @astryxdesign/theme-neutral ${themeVersion} (MIT). Do not edit by hand.
package com.pleos.routine.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/** Astryx palette families; node categories pick one (see design/flow-visuals.mjs). */
enum class Hue { ${hues.map(h => h.toUpperCase()).join(', ')} }

/** Pale fill, strong icon, readable text and border of one palette family. */
data class HueColors(val background: Color, val icon: Color, val text: Color, val border: Color)

/** Semantic Astryx colours for one mode. Status text on a muted fill uses the matching hue's text colour. */
data class AstryxColors(
${Object.keys(roles).map(k => `    val ${k}: Color,`).join('\n')}
    val hues: Map<Hue, HueColors>,
) {
    fun hue(h: Hue): HueColors = hues.getValue(h)
    val onSuccessMuted: Color get() = hue(Hue.GREEN).text
    val onErrorMuted: Color get() = hue(Hue.RED).text
    val onInfoMuted: Color get() = hue(Hue.BLUE).text
    val onWarningMuted: Color get() = hue(Hue.YELLOW).text
}

/** --radius-inner / -element / -container / -page. */
object AstryxRadius { val inner = 6.dp; val element = 10.dp; val container = 12.dp; val page = 28.dp }

val AstryxLight = ${scheme('light')}

val AstryxDark = ${scheme('dark')}
`);
}

const count = await writeIcons();
writeTokens();
console.log(`wrote ${count} icons and AstryxTokens.kt (theme-neutral ${themeVersion}, lucide-react ${lucideVersion})`);
